/**
 * Generates the WhatsApp URL with pre-filled message according to user requirements
 */
export function buildWhatsAppUrl(data: BookingFormData): string {
  const parts: string[] = [
    'السلام عليكم أستاذة أسماء عبدالكريم، أرغب في الاستفسار عن رحلة عمرة لمدة 15 يومًا.',
    '',
    `الاسم: ${data.fullName.trim()}`,
    `رقم الهاتف: ${data.phone.trim()}`,
    `مسار الرحلة: ${data.route}`,
    `الباقة: ${data.packageType}`,
    `الوجبات: ${data.meals}`,
  ];

  if (data.travelDate && data.travelDate.trim() !== '') {
    parts.push(`موعد السفر: ${data.travelDate.trim()}`);
  }

  if (data.travelersCount && data.travelersCount.trim() !== '') {
    parts.push(`عدد المسافرين: ${data.travelersCount.trim()}`);
  }

  if (data.notes && data.notes.trim() !== '') {
    parts.push(`ملاحظات إضافية: ${data.notes.trim()}`);
  }

  parts.push('');
  parts.push('أرجو إرسال تفاصيل الرحلة والسعر والخدمات المشمولة. شكرًا لكم.');

  const messageText = parts.join('\n');
  return `https://wa.me/${SITE_CONFIG.whatsappEgyptDigits}?text=${encodeURIComponent(messageText)}`;
}

